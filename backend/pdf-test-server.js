const express = require('express');
const cors = require('cors');
const puppeteer = require('puppeteer');

const app = express();
app.use(cors());
app.use(express.json());

// Simple test endpoint for PDF generation
app.post('/test-pdf', async (req, res) => {
    let browser;
    try {
        console.log('Starting PDF generation test...');
        
        browser = await puppeteer.launch({
            headless: 'new',
            args: [
                '--no-sandbox', 
                '--disable-setuid-sandbox',
                '--disable-dev-shm-usage'
            ]
        });
        
        const page = await browser.newPage();
        
        const testHtml = `
        <!DOCTYPE html>
        <html>
        <head>
            <meta charset="utf-8">
            <style>
                body { font-family: Arial, sans-serif; padding: 20px; }
                table { border-collapse: collapse; width: 100%; }
                th, td { border: 1px solid black; padding: 8px; }
            </style>
        </head>
        <body>
            <h1>Test PDF Document</h1>
            <p>This is a test PDF generated by Puppeteer.</p>
            <table>
                <tr><th>Column 1</th><th>Column 2</th></tr>
                <tr><td>Data 1</td><td>Data 2</td></tr>
            </table>
        </body>
        </html>
        `;
        
        await page.setContent(testHtml, { waitUntil: 'networkidle0' });
        
        const pdfBuffer = await page.pdf({
            format: 'A4',
            printBackground: true
        });
        
        await browser.close();
        
        console.log('PDF generated successfully, size:', pdfBuffer.length);
        
        res.set({
            'Content-Type': 'application/pdf',
            'Content-Disposition': 'attachment; filename="test.pdf"',
            'Content-Length': pdfBuffer.length
        });
        res.send(pdfBuffer);
        
    } catch (error) {
        console.error('Error generating test PDF:', error);
        if (browser) {
            await browser.close();
        }
        res.status(500).json({ 
            message: 'Error generating test PDF',
            error: error.message 
        });
    }
});

const PORT = 5001;
app.listen(PORT, () => {
    console.log(`PDF test server running on port ${PORT}`);
});
